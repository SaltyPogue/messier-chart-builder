_NGC_RE = re.compile(r"(?<![a-z0-9])(?:ngc|n)[\s_\-.]*0*(\d{1,4})(?!\d)", re.I)
_M_RE = re.compile(r"(?<![a-z0-9])(?:messier|m)[\s_\-.]*0*(\d{1,3})(?!\d)", re.I)
_C_RE = re.compile(r"(?<![a-z0-9])(?:caldwell|c)[\s_\-.]*0*(\d{1,3})(?!\d)", re.I)


def index_for_number(num):
    return INDEX.get(num)


def parse_number(name):
    """Return the square for a file name such as 'NGC 891.jpg', 'ngc7814', 'M33' or 'C23', or None."""
    for m in _NGC_RE.finditer(name):
        hit = INDEX.get(int(m.group(1)))
        if hit:
            return hit
    for m in _M_RE.finditer(name):
        ngc = MESSIER_TO_NGC.get(int(m.group(1)))
        if ngc:
            return INDEX[ngc]
    for m in _C_RE.finditer(name):
        ngc = CALDWELL_TO_NGC.get(int(m.group(1)))
        if ngc:
            return INDEX[ngc]
    return None
