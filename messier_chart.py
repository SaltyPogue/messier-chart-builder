        try:
            if f.lower().endswith((".jpg", ".jpeg")):
                self.chart.save(f, quality=95, subsampling=0)
            else:
                self.chart.save(f)
            self.status_var.set(f"Exported to {f}")
        except Exception as ex:
            messagebox.showerror("Export failed", str(ex))

