_MESSIER_RE = re.compile(r"(?<![a-z0-9])(?:messier|m)[\s_\-.]*0*(\d{1,3})(?!\d)", re.I)


def parse_messier(name):
    """Return the Messier number found in a file name, or None."""
    for m in _MESSIER_RE.finditer(name):
        n = int(m.group(1))
        if 1 <= n <= 110:
            return n
    return None


