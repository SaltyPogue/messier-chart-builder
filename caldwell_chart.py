    def import_files(self, paths, target=None):
        files = []
        for p in paths:
            p = Path(p)
            if p.is_dir():
                files += sorted(f for f in p.iterdir() if f.suffix.lower() in IMAGE_EXT)
            elif p.suffix.lower() in IMAGE_EXT:
                files.append(p)
        if not files:
            messagebox.showinfo("No photos", "None of those files are supported images "
                                "(JPG, PNG, TIFF, BMP, WebP, GIF).")
            return

        single = len(files) == 1
        added, skipped = [], []
        self.root.config(cursor="watch")
        self.root.update_idletasks()
        try:
            for f in files:
                n = parse_number(f.stem)
                if n is None and single:
                    n = target or self.ask_number(f)
                if n is None:
                    skipped.append(f"{f.name}: no Caldwell or NGC/IC number in the file name")
                    continue
                if single and cell_path(n).exists() and not messagebox.askyesno(
                        "Replace photo?", f"{PREFIX}{n} already has a photo. Replace it with {f.name}?"):
                    return
                self.status_var.set(f"Adding {f.name} as {PREFIX}{n}…")
                self.root.update_idletasks()
                try:
                    import_photo(f, n)
                    added.append(n)
                except Exception as ex:
                    skipped.append(f"{f.name}: {ex}")
        finally:
            self.root.config(cursor="")

        if added:
            self.rebuild()
            labels = ", ".join(f"{PREFIX}{n}" for n in sorted(set(added)))
            self.status_var.set(f"Added {labels}. Chart saved to {CHART_FILE}")
        if skipped:
            messagebox.showwarning(
                "Some photos were skipped",
                "\n".join(skipped[:25]) + ("\n…" if len(skipped) > 25 else "") +
                "\n\nTip: name files like C20.jpg or NGC 7000.jpg, or drop them one at a time onto a cell.")

